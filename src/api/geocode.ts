// Normalize: lowercase, remove whitespace
function norm(s: string) {
  return s.toLowerCase().replace(/\s+/g, '')
}

export function searchLocations(query: string, maxResults = 5): GeoResult[] {
  const q = norm(query)
  if (q.length < 1) return []

  // Exact matches first, then prefix, then contains
  const exact: GeoResult[] = []
  const prefix: GeoResult[] = []
  const contains: GeoResult[] = []

  for (const loc of LOCATIONS) {
    const dn = norm(loc.displayName)
    if (dn === q) {
      exact.push(loc)
    } else if (dn.startsWith(q)) {
      prefix.push(loc)
    } else if (dn.includes(q)) {
      contains.push(loc)
    }
  }

  // Deduplicate by displayName
  const seen = new Set<string>()
  const results: GeoResult[] = []
  for (const r of [...exact, ...prefix, ...contains]) {
    if (!seen.has(r.displayName)) {
      seen.add(r.displayName)
      results.push(r)
    }
  }
  return results.slice(0, maxResults)
}
